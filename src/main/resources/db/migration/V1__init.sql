CREATE TABLE public.category (
    id int8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "name" varchar(255) NULL
);

CREATE TABLE public.products (
    id int8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "name" varchar(255) NULL,
    price numeric(38, 2) NULL,
    quantity int4 NULL,
    category_id int8 NULL,
    CONSTRAINT fk_products_category FOREIGN KEY (category_id) REFERENCES public.category(id)
);

CREATE TABLE public.customer (
    id int8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    address varchar(255) NULL,
    email varchar(255) NULL UNIQUE,
    "name" varchar(255) NULL,
    "password" varchar(255) NULL,
    "role" varchar(255) NULL,
    lock_time timestamp(6) NULL,
    failed_attempts int4 DEFAULT 0 NULL
);

CREATE TABLE public.orders (
    id int8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "date" timestamp(6) NULL,
    status varchar(255) NULL,
    customer_id int8 NULL,
    CONSTRAINT fk_orders_customer FOREIGN KEY (customer_id) REFERENCES public.customer(id)
);

CREATE TABLE public.order_item (
    id int8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    price numeric(38, 2) NULL,
    quantity int4 NULL,
    order_id int8 NULL,
    product_id int8 NULL,
    CONSTRAINT fk_order_item_product FOREIGN KEY (product_id) REFERENCES public.products(id),
    CONSTRAINT fk_order_item_order FOREIGN KEY (order_id) REFERENCES public.orders(id)
);

CREATE TABLE public.refresh_token (
    id int8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    expiry_date timestamp(6) NULL,
    "token" varchar(255) NULL,
    customer_id int8 NULL UNIQUE,
    CONSTRAINT fk_refresh_token_customer FOREIGN KEY (customer_id) REFERENCES public.customer(id)
);